"""Selected CUT/CLIP runtime comparison and Drone threshold trade-off."""
import math
import os
from collections import Counter


DRONE_ID = "drone_drone_prbmax_N5-R3"
MATCHED_EXPONENT = 12
CLIP_RESOLUTION = 2
METHODS = (("cut", "plotcut", "o"), ("clip", "plotclip", "triangle"))
DRONE_SERIES = (
    ("cut", None, "plotcut", "o", r"\config{cut}"),
    ("clip", 2, "plotclip", "triangle", r"\config{clip}, $\eta=2$"),
    ("clip", 3, "plotdiscr", "square", r"\config{clip}, $\eta=3$"),
)


def save_outputs(p, execution, instances, timelimit=None):
    if timelimit is None:
        timelimit = p.storm.META_CONFIG_TIMELIMITS[0]
    root = os.path.join(p.OUT_DIR, "underapprox-plots")
    os.makedirs(root, exist_ok=True)
    included = [b for b in p.benchmarks.INSTANCES if b["id"] in instances]
    example = next((b for b in included if b["id"] == DRONE_ID), None)
    if example is None:
        raise ValueError(f"Missing selected Drone example: {DRONE_ID}")

    def run(inst, method, exponent, resolution=CLIP_RESOLUTION):
        config = f"cut{exponent:02}" if method == "cut" else f"clip{exponent:02}res{resolution:02}"
        return p.get_result(execution, p.storm.NAME, config, inst)

    def success(result):
        return p.is_successful_result(result, timelimit)

    def status(result):
        if result is None:
            return "not-run"
        if success(result):
            return "successful"
        if not result.get("timeout") and -9 in result.get("return-codes", []):
            return "killed"
        for key, name in (("timeout", "timeout"), ("memout", "memout"),
                          ("execution-error", "execution-error")):
            if result.get(key):
                return name
        return "failed"

    def plot_status(result):
        outcome = status(result)
        return "memout" if outcome == "killed" else outcome

    def runtime(result):
        time = result["wallclock-time"]
        if not math.isfinite(time) or time <= 0:
            raise ValueError(f"Invalid successful runtime: {result['id']}")
        return time

    def write(filename, body, styled=True):
        with open(os.path.join(root, filename), "w") as output:
            output.write("% Generated by scripts/underapprox_comparison_visuals.py.\n")
            output.write(p.style_latex_plot(body) if styled else body)

    def csv(filename, rows):
        p.save_csv([["nan" if c is None else c for c in row] for row in rows],
                   os.path.join(root, filename))

    def axis(options, body):
        return (r"\begin{tikzpicture}\begin{axis}[" + "\n" + options + "]\n"
                + body + r"\end{axis}\end{tikzpicture}" + "\n")

    # Matched parameters compare exploration methods, with failures explicitly
    # outside the numeric runtime region. Clamping affects display only.
    lower = 0.1
    categories = [("timeout", "TO"), ("memout", "MO"), ("error", "ERR")]
    if any(run(b["id"], method, MATCHED_EXPONENT) is None
           for b in included for method, *_ in METHODS):
        categories.append(("not-run", "n/a"))
    # Equal log-space distances are layout slots, never measured runtimes.
    category_step = 0.38
    category_positions = {
        name: timelimit * 10 ** (category_step * index)
        for index, (name, _) in enumerate(categories, 1)
    }
    limit = timelimit * 10 ** (category_step * (len(categories) + 0.5))
    points = {kind: [["cut", "clip"]] for kind in ("prb", "rew")}
    matched = [["instance", "objective", "cut-config", "clip-config", "cut-time", "clip-time",
                "cut-bound", "clip-bound", "cut-status", "clip-status",
                "cut-plot-status", "clip-plot-status", "cut-plot-position", "clip-plot-position"]]
    successes = {"cut": 0, "clip": 0}
    for benchmark in included:
        results = [run(benchmark["id"], method, MATCHED_EXPONENT) for method, *_ in METHODS]
        times, bounds, display, plot_statuses = [], [], [], []
        for (method, *_), result in zip(METHODS, results):
            time = runtime(result) if success(result) else None
            bound = p.parse_result_value(result["result"])[1] if success(result) else None
            times.append(time)
            bounds.append(bound)
            outcome = status(result)
            category = ("memout" if outcome in ("killed", "memout") else outcome
                        if outcome in ("successful", "timeout", "not-run") else "error")
            plot_statuses.append(category)
            display.append(max(lower, time) if time is not None else category_positions[category])
            successes[method] += time is not None
        points[benchmark["property"]["type"]].append(display)
        matched.append([benchmark["id"], benchmark["property"]["type"] + benchmark["property"]["dir"],
                        f"cut{MATCHED_EXPONENT:02}", f"clip{MATCHED_EXPONENT:02}res{CLIP_RESOLUTION:02}",
                        *times, *bounds, *map(status, results), *plot_statuses, *display])
    csv("matched-runtime.csv", matched)
    guides = []
    for line in (f"({timelimit},{lower}) ({timelimit},{limit})",
                 f"({lower},{timelimit}) ({limit},{timelimit})"):
        guides.append(r"\addplot[black!35,thin,no marks,forget plot] coordinates {" + line + "};\n")
    for coordinates, style in ((f"({lower},{lower}) ({timelimit},{timelimit})", "solid"),
                               (f"({lower},{2 * lower}) ({timelimit / 2},{timelimit})", "densely dotted"),
                               (f"({2 * lower},{lower}) ({timelimit},{timelimit / 2})", "densely dotted")):
        guides.append(r"\addplot[black!60,thin,no marks,forget plot," + style + "] coordinates {"
                      + coordinates + "};\n")
    for kind, color, mark, label in (("prb", "plotdiscr", "o", "probability"),
                                    ("rew", "plotclip", "triangle", "reward")):
        guides.append(r"\addplot[only marks,color=" + color + ",mark=" + mark
                      + r",mark size=1.5pt,mark options={fill=none},line width=0.4pt]"
                      + r" table[x=cut,y=clip,col sep=space,row sep=\\]{"
                      + p.latex_plot_table(points[kind]) + "};\n"
                      + r"\addlegendentry{" + label + "}\n")
    category_ticks = ",".join(f"{category_positions[name]:.12g}" for name, _ in categories)
    category_labels = ",".join(label for _, label in categories)
    failure_tick_options = "".join(
        f"extra {axis} ticks={{{category_ticks}}},"
        + f"extra {axis} tick labels={{{category_labels}}},"
        + f"extra {axis} tick style={{grid=major,minor tick num=0,"
        + "major grid style={draw=black!15,line width=0.25pt,solid}},"
        for axis in ("x", "y")
    )
    scatter_options = (p.LATEX_SCATTER_OPTIONS
                       + r"width=0.83\linewidth,height=0.83\linewidth,xmode=log,ymode=log,"
                       + f"xmin={lower},xmax={limit},ymin={lower},ymax={limit},"
                       + p.scatter_log_ticks(lower, timelimit)
                       + failure_tick_options
                       + r"xlabel={CUT runtime (s)},ylabel={CLIP runtime (s)},")
    write("matched-runtime.tex", axis(scatter_options, "".join(guides)))

    # Sweep the threshold for CUT and two fixed clipping resolutions.
    observations = [["instance", "method", "exponent", "threshold", "resolution", "bound", "time", "states",
                     "measured-runtime", "status", "plot-status"]]
    tables = {(method, resolution): [["threshold", "bound", "time", "states"]]
              for method, resolution, *_ in DRONE_SERIES}
    failures = {key: {outcome: [] for outcome in ("timeout", "memout", "failed")} for key in tables}
    example_successes = {key: 0 for key in tables}
    state_observations = {key: 0 for key in tables}
    for exponent in range(8, 33):
        for method, resolution, *_ in DRONE_SERIES:
            key = (method, resolution)
            result = run(DRONE_ID, method, exponent, resolution)
            bound, time, states = None, None, None
            if success(result):
                relation, bound = p.parse_result_value(result["result"])
                if relation not in ("=", p.expected_bound_relation(method, example)):
                    raise ValueError(f"Unexpected bound direction: {result['id']}")
                time = runtime(result)
                states = (result.get("belief-mdp") or {}).get("states")
                if states is not None:
                    if not isinstance(states, int) or states <= 0:
                        raise ValueError(f"Invalid belief-MDP state count: {result['id']}")
                    state_observations[key] += 1
                example_successes[key] += 1
            threshold = 2 ** exponent
            tables[key].append([threshold, bound if bound is not None else "nan",
                                time if time is not None else "nan",
                                states if states is not None else "nan"])
            outcome = plot_status(result)
            if outcome not in ("successful", "not-run"):
                failures[key][outcome if outcome in ("timeout", "memout") else "failed"].append(threshold)
            observations.append([DRONE_ID, method, exponent, threshold,
                                 resolution, bound, time, states,
                                 result.get("wallclock-time") if result else None, status(result), outcome])
    csv("drone-threshold.csv", observations)
    count_text = (f"successful thresholds: CUT {example_successes['cut', None]}/25; "
                  + rf"CLIP $\eta=2$: {example_successes['clip', 2]}/25; "
                  + rf"CLIP $\eta=3$: {example_successes['clip', 3]}/25")
    counts = (r"\node[anchor=south west,font=\scriptsize] at (axis description cs:0,1.04) {"
              + count_text + "};\n")

    # Audit the evidence across the entire explicit-threshold sweep, retaining
    # killed separately from allocation failures even though the plot groups MO.
    outcomes = [["method", "resolution", "successful", "timeout", "killed", "memout", "other", "not-run"]]
    for method, resolution, *_ in DRONE_SERIES:
        totals = Counter(status(run(b["id"], method, exponent, resolution))
                         for b in included for exponent in range(8, 33))
        outcomes.append([method, resolution, *[totals[s] for s in ("successful", "timeout", "killed", "memout")],
                         sum(v for k, v in totals.items() if k not in
                             ("successful", "timeout", "killed", "memout", "not-run")), totals["not-run"]])
    csv("run-outcomes.csv", outcomes)

    # Two alternative views of the full CUT sweep: individual instances and
    # aggregate counts. Both derive from exactly the same classified runs.
    outcome_styles = (
        ("successful", "plotcut!55", "successful"),
        ("timeout", "orange!80", "TO"),
        ("memout", "plotclip!75", "MO"),
        ("failed", "black!55", "other failure"),
        ("not-run", "black!10", "not run"),
    )
    ordered = sorted(included, key=lambda b: b["benchmark-set"])
    cutoff_rows = [["instance", "label", "row", "family", "objective", "exponent", "threshold",
                    "status", "plot-status", "measured-runtime"]]
    per_threshold = {e: Counter() for e in range(8, 33)}
    cells, labels, boundaries = [], [], []
    colors = {name: color for name, color, _ in outcome_styles}
    previous_family = None
    for index, benchmark in enumerate(ordered, 1):
        family = benchmark["benchmark-set"]
        if previous_family is not None and family != previous_family:
            boundaries.append(index - 0.5)
        previous_family = family
        name = family if benchmark["name"] == "crypt" else benchmark["name"]
        name = p.LATEX_MODEL_ABBREVIATIONS.get(name, name)
        parameters = (benchmark["model"].get("open-parameters") or {}).values()
        parameter_label = "-".join(f"{v:g}" if isinstance(v, (int, float)) else str(v) for v in parameters)
        objective = benchmark["property"]["id"]
        symbol = "P" if benchmark["property"]["type"] == "prb" else "R"
        subscript = r"\min" if benchmark["property"]["dir"] == "min" else r"\max"
        if objective.endswith("packets"):
            subscript += r",\mathrm{pkt}"
        label = (r"\textsc{" + name + ("/" + parameter_label if parameter_label else "")
                 + "} $" + symbol + "_{" + subscript + "}$")
        labels.append(label)
        for exponent in range(8, 33):
            result = run(benchmark["id"], "cut", exponent)
            source = status(result)
            plotted = plot_status(result)
            if plotted not in colors:
                plotted = "failed"
            per_threshold[exponent][plotted] += 1
            if source == "killed":
                per_threshold[exponent]["killed"] += 1
            elif source == "memout":
                per_threshold[exponent]["allocation-memout"] += 1
            cutoff_rows.append([benchmark["id"], label, index, family, objective,
                                exponent, 2 ** exponent, source, plotted,
                                result.get("wallclock-time") if result else None])
            cells.append(r"\path[fill=" + colors[plotted] + r",draw=white,line width=0.15pt]"
                         + f" (axis cs:{exponent - 0.5},{index - 0.5}) rectangle"
                         + f" (axis cs:{exponent + 0.5},{index + 0.5});\n")
    csv("cut-outcomes-instances.csv", cutoff_rows)
    summaries = [["exponent", "threshold", *[name for name, _, _ in outcome_styles],
                  "killed", "allocation-memout"]]
    for exponent, counts_at_threshold in per_threshold.items():
        summaries.append([exponent, 2 ** exponent,
                          *[counts_at_threshold[name] for name, _, _ in outcome_styles],
                          counts_at_threshold["killed"], counts_at_threshold["allocation-memout"]])
    csv("cut-outcomes-counts.csv", summaries)
    active = [entry for entry in outcome_styles if any(c[entry[0]] for c in per_threshold.values())]
    outcome_legend = "".join(r"\addlegendimage{area legend,fill=" + color + r",draw=black!30}"
                             + "\n" + r"\addlegendentry{" + label + "}\n"
                             for _, color, label in active)
    threshold_axis = (
        r"xmin=7.5,xmax=32.5,xtick={8,12,16,20,24,28,32},"
        + r"xticklabels={$2^8$,$2^{12}$,$2^{16}$,$2^{20}$,$2^{24}$,$2^{28}$,$2^{32}$},"
        + "minor xtick={" + ",".join(str(e) for e in range(8, 33) if e not in (8, 12, 16, 20, 24, 28, 32)) + "},"
        + r"xlabel={exploration threshold $\tau$},tick align=outside,"
        + r"major tick length=2pt,minor tick length=1.3pt,"
        + r"tick style={black,line width=0.3pt},"
        + r"xticklabel style={font=\footnotesize},"
        + r"legend columns=-1,legend style={draw=black!60,line width=0.3pt,fill=white},"
    )
    # Measure the actual longest label, reserving its width in the B5 layout.
    measured = [r"\dimen0=0pt" + "\n"]
    for label in labels:
        measured.append(r"\settowidth{\dimen2}{\scriptsize " + label + "}\n"
                        + r"\ifdim\dimen2>\dimen0 \dimen0=\dimen2\fi" + "\n")
    measured.append(r"\edef\cutOutcomeAxisWidth{\the\dimexpr\linewidth-\dimen0-5mm\relax}" + "\n")
    heatmap_options = (threshold_axis + r"scale only axis,width=\cutOutcomeAxisWidth,"
                       + f"height={max(12, len(ordered) * 2.8):g}mm,ymin=0.5,ymax={len(ordered) + 0.5},y dir=reverse,"
                       + "ytick={" + ",".join(str(i) for i in range(1, len(ordered) + 1)) + "},"
                       + "yticklabels={" + ",".join("{" + label + "}" for label in labels) + "},"
                       + r"yticklabel style={font=\scriptsize},ytick style={draw=none},"
                       + r"axis y line=left,enlarge y limits=false,grid=none,")
    for boundary in boundaries:
        cells.append(r"\draw[black!45,line width=0.3pt]"
                     + f" (axis cs:7.5,{boundary}) -- (axis cs:32.5,{boundary});\n")
    write("cut-outcomes-heatmap.tex", "".join(measured) + axis(heatmap_options, "".join(cells) + outcome_legend))
    total = len(ordered)
    bars_options = (threshold_axis + r"width=\dimexpr\linewidth-6mm\relax,height=4.5cm,"
                    + f"ymin=0,ymax={total},enlarge y limits=false,"
                    + "ytick={" + ",".join(map(str, sorted({*range(0, total, 10), total}))) + "},"
                    + r"ylabel={benchmark instances},ybar stacked,bar width=7pt,"
                    + r"ymajorgrids=true,major grid style={black!15,line width=0.25pt},")
    bars = []
    for outcome, color, label in active:
        bars.append(r"\addplot[fill=" + color + r",draw=white,line width=0.15pt]"
                    + r" table[x=exponent,y=" + outcome + r",col sep=space,row sep=\\]{"
                    + p.latex_plot_table(summaries) + "};\n"
                    + r"\addlegendentry{" + label + "}\n")
    write("cut-outcomes-stacked.tex", axis(bars_options, "".join(bars)))

    # Match the tool-paper gap measure, using each instance's tightest observed
    # successful explicit CUT run as reference. Zero references are retained.
    gap_rows = [["instance", "objective", "exponent", "threshold", "bound", "reference-bound",
                 "reference-config", "reference-runtime", "baseline-bound", "gap-percent",
                 "improves-baseline", "status", "plot-status"]]
    gaps = {e: [] for e in range(8, 33)}
    baseline_improved = {e: 0 for e in range(8, 33)}
    improved_instances = set()
    for benchmark in ordered:
        inst = benchmark["id"]
        available = []
        for exponent in range(8, 33):
            result = run(inst, "cut", exponent)
            if success(result):
                relation, bound = p.parse_result_value(result["result"])
                if relation not in ("=", p.expected_bound_relation("cut", benchmark)):
                    raise ValueError(f"Unexpected CUT bound direction: {result['id']}")
                bound = p.comparison_value(bound)
                if not math.isfinite(bound):
                    raise ValueError(f"Non-finite CUT bound: {result['id']}")
                available.append((exponent, result, bound))
        maximise = benchmark["property"]["dir"] == "max"
        best = min(available, key=lambda item: ((-1 if maximise else 1) * item[2], runtime(item[1])), default=None)
        baseline = next((value for exponent, _, value in available if exponent == 8), None)
        values = {exponent: value for exponent, _, value in available}
        for exponent in range(8, 33):
            result = run(inst, "cut", exponent)
            bound = values.get(exponent)
            gap, improves = None, None
            if bound is not None and best is not None:
                scale = max(abs(bound), abs(best[2]))
                gap = 100 * abs(bound - best[2]) / scale if scale else 0
                gaps[exponent].append(gap)
                if baseline is not None:
                    improves = int(bound > baseline if maximise else bound < baseline)
                    baseline_improved[exponent] += improves
                    if improves:
                        improved_instances.add(inst)
            gap_rows.append([inst, benchmark["property"]["id"], exponent, 2 ** exponent,
                             bound, best[2] if best else None,
                             f"cut{best[0]:02}" if best else None, runtime(best[1]) if best else None,
                             baseline, gap, improves, status(result), plot_status(result)])
    csv("cut-bound-gaps.csv", gap_rows)
    gap_summary = [["exponent", "threshold", "successful", "improved-over-baseline",
                    "minimum", "q25", "median", "q75", "maximum"]]
    boxplots = []
    for exponent, values in gaps.items():
        summary_values = ([min(values), *[p.plot_quantile(values, q) for q in (0.25, 0.5, 0.75)], max(values)]
                          if values else [None] * 5)
        gap_summary.append([exponent, 2 ** exponent, len(values), baseline_improved[exponent], *summary_values])
        boxplots.append(p.prepared_boxplot(values, exponent, "plotcut")
                        .replace("boxplot/box extend=0.24", "boxplot/box extend=0.55")
                        .replace("draw=plotcut,", "draw=plotcut!70!black,"))
    csv("cut-bound-gap-summary.csv", gap_summary)
    max_gap = max((value for values in gaps.values() for value in values), default=100)
    gap_upper = max(100, math.ceil(max_gap / 25) * 25)
    gap_options = (threshold_axis + r"width=\dimexpr\linewidth-6mm\relax,height=4.5cm,"
                   + f"ymin=-3,ymax={gap_upper + 3},"
                   + "ytick={" + ",".join(str(t) for t in range(0, gap_upper + 1, 25)) + "},"
                   + r"minor y tick num=1,ylabel={gap to best CUT bound (\%)},"
                   + r"ymajorgrids=true,major grid style={black!15,line width=0.25pt},")
    write("cut-bound-gap.tex", "% Preamble also requires \\usepgfplotslibrary{statistics}.\n"
          + axis(gap_options, "".join(boxplots)))
    write("cut-bound-overview.tex", r"""% Preamble requires pgfplots and \usepgfplotslibrary{statistics}.
\makebox[\linewidth][r]{\input{underapprox-plots/cut-bound-gap.tex}}\par\bigskip
\makebox[\linewidth][r]{\input{underapprox-plots/cut-outcomes-stacked.tex}}\par
""", styled=False)

    ticks = (8, 12, 16, 20, 24, 28, 32)
    def threshold_minor_ticks(labelled):
        return "minor xtick={" + ",".join(str(2 ** k) for k in range(8, 33) if k not in labelled) + "},"

    def log_y_minor_ticks(lower_exponent, upper_exponent, maximum):
        values = [m * 10 ** k for k in range(lower_exponent, upper_exponent + 1)
                  for m in range(2, 10) if m * 10 ** k < maximum]
        return "minor ytick={" + ",".join(f"{value:g}" for value in values) + "},"

    common = (r"width=\dimexpr\linewidth-6mm\relax,height=4.5cm,"
              + r"grid=major,major grid style={draw=black!15,line width=0.25pt},"
              + r"tick align=outside,axis line style={line width=0.4pt},"
              + r"major tick length=2pt,minor tick length=1.3pt,"
              + r"major tick style={black,line width=0.3pt},minor tick style={black!70,line width=0.25pt},"
              # Explicit power-of-two ticks retain the threshold scale while
              # using the log base supported by PGFPlots' minor-tick renderer.
              + r"xmode=log,scaled x ticks=false,"
              + f"xmin={2 ** 8},xmax={2 ** 32},"
              + "xtick={" + ",".join(str(2 ** k) for k in ticks) + "},"
              + "xticklabels={" + ",".join(f"$2^{{{k}}}$" for k in ticks) + "},"
              + threshold_minor_ticks(ticks)
              + r"xlabel={exploration threshold $\tau$},unbounded coords=jump,clip=false,")
    failure_groups = [outcome for outcome in ("timeout", "memout", "failed")
                      if any(groups[outcome] for groups in failures.values())]
    numeric_fraction = 0.94 - 0.11 * len(failure_groups)
    for metric in ("bound", "time", "states"):
        options = common
        if metric == "bound":
            options += r"ymin=0.58,ymax=1.015,ytick={0.6,0.7,0.8,0.9,1},ylabel={probability lower bound},"
            options += r"minor ytick={0.65,0.75,0.85,0.95},"
            numeric_lower, numeric_upper, logarithmic = 0.58, 1.015, False
        elif metric == "time":
            time_ticks = [10 ** e for e in range(-1, math.floor(math.log10(timelimit)) + 1)]
            if timelimit not in time_ticks:
                time_ticks.append(timelimit)
            options += (r"ymode=log,ymin=0.1,ylabel={runtime (s)},"
                        + "ytick={" + ",".join(f"{t:g}" for t in time_ticks) + "},"
                        + "yticklabels={" + ",".join(f"${t:g}$" for t in time_ticks) + "},")
            options += log_y_minor_ticks(-1, math.floor(math.log10(timelimit)), timelimit)
            numeric_lower, numeric_upper, logarithmic = 0.1, timelimit, True
        elif metric == "states":
            options += (r"ymode=log,ymin=100,ymax=100000000,ylabel={belief-MDP states},"
                        + r"ytick={100,1000,10000,100000,1000000,10000000,100000000},"
                        + r"yticklabels={$10^2$,$10^3$,$10^4$,$10^5$,$10^6$,$10^7$,$10^8$},")
            options += log_y_minor_ticks(2, 7, 100000000)
            numeric_lower, numeric_upper, logarithmic = 100, 100000000, True
        def level(fraction):
            if logarithmic:
                span = math.log10(numeric_upper / numeric_lower) / numeric_fraction
                return numeric_lower * 10 ** (span * fraction)
            return numeric_lower + (numeric_upper - numeric_lower) / numeric_fraction * fraction

        positions = {outcome: level(numeric_fraction + 0.11 * (i + 1))
                     for i, outcome in enumerate(failure_groups)}
        options += f"ymax={level(1)},enlarge y limits=false,"
        options += ("extra y ticks={" + ",".join(f"{positions[o]:.12g}" for o in failure_groups) + "},"
                    + "extra y tick labels={" + ",".join(
                        {"timeout": "TO", "memout": "MO", "failed": "ERR"}[o] for o in failure_groups) + "},"
                    + r"extra y tick style={grid=none,minor tick num=0},")
        curves, legend = [], []
        for method, resolution, color, mark, label in DRONE_SERIES:
            curves.append(r"\addplot[only marks,color=" + color + ",mark=" + mark
                          + r",mark size=1.5pt,mark options={fill=white},forget plot]"
                          + r" table[x=threshold,y=" + metric + r",col sep=space,row sep=\\]{"
                          + p.latex_plot_table(tables[method, resolution]) + "};\n")
